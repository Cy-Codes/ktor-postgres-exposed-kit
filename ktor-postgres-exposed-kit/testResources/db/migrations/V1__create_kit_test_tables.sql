CREATE SCHEMA IF NOT EXISTS app_kit;
CREATE SCHEMA IF NOT EXISTS telemetry_kit;

CREATE TABLE app_kit.items (
    id UUID PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE telemetry_kit.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT NOT NULL,
    payload TEXT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

REVOKE ALL ON SCHEMA app_kit FROM PUBLIC;
REVOKE ALL ON SCHEMA telemetry_kit FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA app_kit FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA telemetry_kit FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kit_read_write') THEN
        GRANT USAGE ON SCHEMA app_kit, telemetry_kit TO kit_read_write;
        GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app_kit TO kit_read_write;
        GRANT SELECT ON ALL TABLES IN SCHEMA telemetry_kit TO kit_read_write;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app_kit, telemetry_kit TO kit_read_write;
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kit_read_only') THEN
        GRANT USAGE ON SCHEMA app_kit, telemetry_kit TO kit_read_only;
        GRANT SELECT ON ALL TABLES IN SCHEMA app_kit TO kit_read_only;
        GRANT INSERT ON telemetry_kit.events TO kit_read_only;
        GRANT USAGE ON SEQUENCE telemetry_kit.events_id_seq TO kit_read_only;
    END IF;
END $$;
